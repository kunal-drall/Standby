#!/usr/bin/env node
// Writes packages/shared/src/abi.ts from Foundry's contracts/out. Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contracts = {
  AllowlistRegistry: 'allowlistRegistryAbi',
  RestrictedAsset: 'restrictedAssetAbi',
  NavOracle: 'navOracleAbi',
  BidBook: 'bidBookAbi',
  StandbyMarket: 'standbyMarketAbi',
};

let out = '// Generated by scripts/export-abi.mjs from contracts/out. Do not edit by hand.\n';
out += "import { erc20Abi } from 'viem';\n\n";
for (const [name, constName] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(root, 'contracts/out', `${name}.sol`, `${name}.json`), 'utf8'));
  out += `export const ${constName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
}
out += 'export const usdtAbi = erc20Abi;\n';
writeFileSync(join(root, 'packages/shared/src/abi.ts'), out);
console.log(`wrote packages/shared/src/abi.ts (${Object.keys(contracts).length} contracts)`);
